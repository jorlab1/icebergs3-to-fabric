-- Run only after external-volume verification succeeds; names must be unused.
CREATE WAREHOUSE FABRIC_POC_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE FABRIC_POC_WH;
CREATE DATABASE FABRIC_ICEBERG_POC;
CREATE SCHEMA FABRIC_ICEBERG_POC.DEMO;

CREATE ICEBERG TABLE FABRIC_ICEBERG_POC.DEMO.ORDERS (
  ORDER_ID NUMBER(9,0),
  CUSTOMER_NAME STRING,
  ORDER_DATE DATE,
  AMOUNT NUMBER(9,2)
)
  CATALOG = 'SNOWFLAKE'
  EXTERNAL_VOLUME = 'FABRIC_POC_S3_VOL'
  BASE_LOCATION = 'orders';

INSERT INTO FABRIC_ICEBERG_POC.DEMO.ORDERS VALUES
  (1, 'Contoso', '2026-11-01', 125.50),
  (2, 'Fabrikam', '2026-11-02', 250.00),
  (3, 'Adventure Works', '2026-11-03', 75.25);

SELECT COUNT(*) AS ROW_COUNT, SUM(AMOUNT) AS TOTAL_AMOUNT
FROM FABRIC_ICEBERG_POC.DEMO.ORDERS;

SELECT SYSTEM$GET_ICEBERG_TABLE_INFORMATION('FABRIC_ICEBERG_POC.DEMO.ORDERS');

ALTER WAREHOUSE FABRIC_POC_WH SUSPEND;
